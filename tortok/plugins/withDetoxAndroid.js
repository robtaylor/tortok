// Expo config plugin: the Android half of Detox's setup
// (https://wix.github.io/Detox/docs/introduction/project-setup), applied at
// `expo prebuild` because android/ is generated, not committed.
//
// The community @config-plugins/detox does the same, but supports Expo only
// up to SDK 53. This covers what tortok needs:
// - Detox's Android library, from the local Maven repo inside node_modules;
// - the test instrumentation runner and the build type the tests run against;
// - the DetoxTest JUnit entry point in androidTest/.
// Cleartext HTTP to the host is already allowed by expo-build-properties'
// usesCleartextTraffic, so no network security config is added.

const fs = require('fs');
const path = require('path');
const { withProjectBuildGradle, withAppBuildGradle, withDangerousMod } = require('@expo/config-plugins');

const MARK = '// detox (plugins/withDetoxAndroid.js)';

/** Insert `text` on the line after the first match of `anchor` (a RegExp). */
function insertAfter(contents, anchor, text, file) {
  if (contents.includes(text)) return contents; // already applied
  const m = anchor.exec(contents);
  if (!m) throw new Error(`withDetoxAndroid: ${anchor} not found in ${file}`);
  const at = m.index + m[0].length;
  return contents.slice(0, at) + '\n' + text + contents.slice(at);
}

const withDetoxProjectGradle = (config) =>
  withProjectBuildGradle(config, (cfg) => {
    cfg.modResults.contents = insertAfter(
      cfg.modResults.contents,
      /allprojects\s*\{\s*repositories\s*\{/,
      `        ${MARK} maven repo\n        maven { url("$rootDir/../node_modules/detox/Detox-android") }`,
      'android/build.gradle',
    );
    return cfg;
  });

const withDetoxAppGradle = (config) =>
  withAppBuildGradle(config, (cfg) => {
    let c = cfg.modResults.contents;
    c = insertAfter(
      c,
      /defaultConfig\s*\{/,
      `        ${MARK} runner\n        testBuildType System.getProperty('testBuildType', 'debug')\n        testInstrumentationRunner 'androidx.test.runner.AndroidJUnitRunner'`,
      'android/app/build.gradle',
    );
    c = insertAfter(
      c,
      /^dependencies\s*\{/m,
      `    ${MARK} library\n    androidTestImplementation('com.wix:detox:+')\n    androidTestImplementation('androidx.test:runner:1.6.2')\n    androidTestImplementation('androidx.test.ext:junit:1.2.1')
    androidTestImplementation('androidx.test:rules:1.6.1')`,
      'android/app/build.gradle',
    );
    cfg.modResults.contents = c;
    return cfg;
  });

const withDetoxTestClass = (config) =>
  withDangerousMod(config, [
    'android',
    async (cfg) => {
      const pkg = cfg.android?.package;
      if (!pkg) throw new Error('withDetoxAndroid: android.package is not set in app.json');
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/androidTest/java', ...pkg.split('.'));
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(
        path.join(dir, 'DetoxTest.java'),
        `package ${pkg};

import com.wix.detox.Detox;
import com.wix.detox.config.DetoxConfig;

import org.junit.Rule;
import org.junit.Test;
import org.junit.runner.RunWith;

import androidx.test.ext.junit.runners.AndroidJUnit4;
import androidx.test.filters.LargeTest;
import androidx.test.rule.ActivityTestRule;

// Generated by plugins/withDetoxAndroid.js at expo prebuild.
@RunWith(AndroidJUnit4.class)
@LargeTest
public class DetoxTest {
    @Rule
    public ActivityTestRule<MainActivity> mActivityRule = new ActivityTestRule<>(MainActivity.class, false, false);

    @Test
    public void runDetoxTests() {
        DetoxConfig detoxConfig = new DetoxConfig();
        detoxConfig.idlePolicyConfig.masterTimeoutSec = 90;
        detoxConfig.idlePolicyConfig.idleResourceTimeoutSec = 60;
        detoxConfig.rnContextLoadTimeoutSec = 180;
        Detox.runTests(mActivityRule, detoxConfig);
    }
}
`,
      );
      return cfg;
    },
  ]);

module.exports = (config) => withDetoxTestClass(withDetoxAppGradle(withDetoxProjectGradle(config)));
